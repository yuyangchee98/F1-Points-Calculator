/**
 * Regenerates the cross-link year lists across the site so every page links to
 * every season. Idempotent — run it after adding new YYYY.astro pages.
 *
 *   node scripts/sync-season-links.mjs
 *
 * Rewrites the block between the season-links markers (one <li> per decade) in:
 *   - src/pages/YYYY.astro    (each omits its own year)
 *   - src/pages/index.astro   ("Select a Season")
 *   - src/pages/[year].astro  ("Other Seasons")
 *   - src/layouts/BaseLayout.astro footer ("Past Seasons", different markup)
 *
 * The listed set = every YYYY.astro page that exists, plus 2025 (served by
 * [year].astro). 2026 is the current season, reached via the "/" link.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pagesDir = join(root, 'src', 'pages');

// A single year-link list item, in either the page or footer markup — the flat
// format this script emitted before the lists were grouped by decade. Only used
// to migrate a file that has no markers yet.
const YEAR_LI = /^(\s*)<li><a href="\/(\d{4})"[^>]*>.*<\/a><\/li>\s*$/;
const START = '<!-- season-links:start (generated by scripts/sync-season-links.mjs) -->';
const END = '<!-- season-links:end -->';

const pageYears = readdirSync(pagesDir)
  .map(f => /^(\d{4})\.astro$/.exec(f))
  .filter(Boolean)
  .map(m => parseInt(m[1], 10));

const LISTED = [...new Set([...pageYears, 2025])].sort((a, b) => b - a);

/** Years newest first, grouped by decade: [['2020s', [2025, …]], …]. */
const byDecade = years => {
  const groups = [];
  for (const y of years) {
    const label = `${Math.floor(y / 10) * 10}s`;
    const last = groups[groups.length - 1];
    if (last?.[0] === label) last[1].push(y);
    else groups.push([label, [y]]);
  }
  return groups;
};

// One <li> per decade. Pages keep the "YYYY F1 Season" anchor text; the footer
// is a compact grid of bare years.
const pageItems = (indent, years) =>
  byDecade(years).map(([label, ys]) =>
    `${indent}<li><strong>${label}:</strong> ${ys.map(y => `<a href="/${y}">${y} F1 Season</a>`).join(', ')}</li>`);

const footerItems = (indent, years) =>
  byDecade(years).map(([label, ys]) =>
    `${indent}<li class="flex gap-2"><span class="w-12 shrink-0 text-gray-500">${label}</span>` +
    `<span class="flex flex-wrap gap-x-2">${ys.map(y => `<a href="/${y}" class="text-gray-300 hover:text-white">${y}</a>`).join(' ')}</span></li>`);

function regenerate(filePath, ownYear, isFooter = false) {
  const lines = readFileSync(filePath, 'utf8').split('\n');

  let start = lines.findIndex(l => l.includes(START));
  let end;
  let indent;
  if (start !== -1) {
    end = lines.findIndex((l, i) => i > start && l.includes(END));
    indent = /^(\s*)/.exec(lines[start])[1];
  } else {
    // First run on this file: replace the maximal contiguous run of flat links.
    start = lines.findIndex(l => YEAR_LI.test(l));
    if (start === -1) {
      console.warn(`  ⚠ no year-link list found in ${filePath}`);
      return;
    }
    end = start;
    while (end + 1 < lines.length && YEAR_LI.test(lines[end + 1])) end++;
    indent = YEAR_LI.exec(lines[start])[1];
  }

  const years = ownYear ? LISTED.filter(y => y !== ownYear) : LISTED;
  const items = isFooter ? footerItems(indent, years) : pageItems(indent, years);
  lines.splice(start, end - start + 1, `${indent}${START}`, ...items, `${indent}${END}`);
  writeFileSync(filePath, lines.join('\n'));
  console.log(`  ✓ ${filePath.replace(root + '/', '')} (${years.length} links${ownYear ? `, omitting ${ownYear}` : ''})`);
}

// Per-year pages (omit own year).
for (const y of pageYears) {
  regenerate(join(pagesDir, `${y}.astro`), y);
}
// Aggregate lists (all years).
regenerate(join(pagesDir, 'index.astro'), null);
regenerate(join(pagesDir, '[year].astro'), null);
regenerate(join(root, 'src', 'layouts', 'BaseLayout.astro'), null, true);

console.log(`\nListed seasons: ${LISTED[0]}…${LISTED[LISTED.length - 1]} (${LISTED.length} years)`);
